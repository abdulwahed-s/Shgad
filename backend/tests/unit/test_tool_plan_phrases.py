@pytest.mark.parametrize("message", WEEKLY_YES)
def test_weekly_plan_general_triggers(message):
    period = resolve_period(message, weekday=0)
    assert weekly_period(message, period) in {"this_week", "last_week"}


@pytest.mark.parametrize("message", WEEKLY_NO)
def test_weekly_plan_leaves_specific_or_uncertain_requests_alone(message):
    assert weekly_period(message, resolve_period(message, weekday=0)) is None


@pytest.mark.parametrize("message", CASH_YES)
def test_cash_plan_general_triggers(message):
    assert cash_request(message, resolve_period(message, weekday=0))


@pytest.mark.parametrize("message", CASH_NO)
def test_cash_plan_leaves_balance_write_and_uncertain_requests_alone(message):
    assert not cash_request(message, resolve_period(message, weekday=0))
